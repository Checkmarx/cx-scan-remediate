// Package cli defines the command line: the flags, their environment variable fallbacks, and the
// validation done before anything is sent to Checkmarx One.
package cli

import (
	"errors"
	"flag"
	"fmt"
	"time"

	"github.com/Checkmarx/cx-scan-remediate/internal/cx1ai"
	"github.com/Checkmarx/cx-scan-remediate/internal/findings"
	"github.com/sirupsen/logrus"
)

// Config holds the value of every flag, after the environment fallbacks are applied.
type Config struct {
	LogLevel string

	ReportFile            string
	RemediateCount        int
	TriageCount           int
	TriageBatchSize       int
	RemediationBatchSize  int
	Engines               string
	Severities            string
	Timeout               time.Duration
	SourceDir             string
	AIPollInterval        time.Duration
	AIPollTimeout         time.Duration
	AIDetailsPollInterval time.Duration
	AIDetailsPollTimeout  time.Duration

	GitHubToken string
	Repo        string
	BaseBranch  string
	PRBranch    string

	Proxy       string
	Insecure    bool
	CACert      string
	NoKeepAlive bool
	KeepTemp    bool

	APIKey       string
	ClientID     string
	ClientSecret string
	BaseURI      string
	BaseAuthURI  string
	Tenant       string
	AccessToken  string
	UserAgent    string
}

// ErrReported marks a command line error that the flag package has already printed, together with
// the usage text.
var ErrReported = errors.New("invalid command line")

// NewFlagSet defines every flag, bound to the returned Config, on a new flag set named name (the
// program name shown in the usage text). version is part of the default user agent.
func NewFlagSet(name, version string) (*flag.FlagSet, *Config) {
	c := &Config{}
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.StringVar(&c.LogLevel, "log-level", "INFO", "Log level: TRACE, DEBUG, INFO, WARNING, ERROR, FATAL")

	fs.StringVar(&c.ReportFile, "report-file", "cx_result.json", "Path to JSON format report as generated by ast-cli --report-format json")
	fs.IntVar(&c.RemediateCount, "remediate-count", 1, "Number of results to remediate, sorted by highest-priority and resultId")
	fs.IntVar(&c.TriageCount, "triage-count", 0, "Number of results to triage, sorted by highest-priority and resultId")
	fs.IntVar(&c.TriageBatchSize, "triage-batch-size", cx1ai.MaxBatchSize, fmt.Sprintf("Number of results submitted to AI Triage together in one request (1-%d)", cx1ai.MaxBatchSize))
	fs.IntVar(&c.RemediationBatchSize, "remediation-batch-size", cx1ai.MaxBatchSize, fmt.Sprintf("Number of results submitted to AI Remediation together in one request (1-%d)", cx1ai.MaxBatchSize))
	fs.StringVar(&c.Engines, "engines", "sast,sca", "Focus only on these engines - comma separated list from: sast,sca")
	fs.StringVar(&c.Severities, "severities", "CRITICAL,HIGH", "Focus only on results of these severities - comma separated list from: CRITICAL,HIGH,MEDIUM,LOW,INFO")
	fs.DurationVar(&c.Timeout, "timeout", 30*time.Minute, "Overall time limit for waiting on AI Triage and AI Remediation, e.g. 30m; 0 for no limit. Work that completes in time is still published as pull requests; unfinished work is abandoned and the run exits non-zero")
	fs.StringVar(&c.SourceDir, "source-dir", ".", "Path to the root of the source code that was scanned, used as the base that remediation diffs are applied to in memory (never modified)")
	fs.DurationVar(&c.AIPollInterval, "ai-poll-interval", 0, "Optional: How often to ask whether an AI Triage or AI Remediation job has finished, e.g. 30s (default: the library's, 30s)")
	fs.DurationVar(&c.AIPollTimeout, "ai-poll-timeout", 0, "Optional: The longest to wait for one finding's AI Triage or AI Remediation job, e.g. 10m (default: the library's, 10m); --timeout still bounds the whole run")
	fs.DurationVar(&c.AIDetailsPollInterval, "ai-details-poll-interval", 0, "Optional: How often to retry fetching the result details of a finished AI job, e.g. 15s (default: the library's, 15s)")
	fs.DurationVar(&c.AIDetailsPollTimeout, "ai-details-poll-timeout", 0, "Optional: The longest to keep retrying that fetch, e.g. 1m (default: the library's, 1m)")

	// repo-scope (classic PAT) or Contents+Pull-requests write (fine-grained) permissions
	fs.StringVar(&c.GitHubToken, "github-token", "", "GitHub token used to publish a pull request with the remediation changes; required when --remediate-count is above 0")
	fs.StringVar(&c.Repo, "repo", "", "Target GitHub repository (owner/repo, HTTP(S) URL, or SSH URL; GitHub.com, GitHub Enterprise Server or a *.ghe.com host) for the pull request; derived from the Checkmarx One project's repoUrl if omitted")
	fs.StringVar(&c.BaseBranch, "base-branch", "", "Branch to open the pull request against; defaults to the repository's default branch")
	fs.StringVar(&c.PRBranch, "pr-branch", "", "Prefix for the names of the branches created for pull requests; each branch is this prefix plus the engine and result ID (default \"cx-remediate/\"). A finding whose branch already exists is skipped")

	fs.StringVar(&c.Proxy, "proxy", "", "Optional: Proxy server (http, https or socks5 URL) for outbound calls to Checkmarx One and GitHub; defaults to the HTTPS_PROXY environment variable")
	fs.BoolVar(&c.Insecure, "insecure", false, "Optional: DISABLE TLS certificate verification for calls to Checkmarx One and GitHub (insecure; prefer --ca-cert)")
	fs.StringVar(&c.CACert, "ca-cert", "", "Optional: Path to a PEM file with extra CA certificate(s) to trust for calls to Checkmarx One and GitHub, e.g. the CA of a TLS-inspecting proxy; added to the system trust store")

	fs.BoolVar(&c.NoKeepAlive, "no-keep-alive", false, "Optional: Disable HTTP connection reuse (a new connection per request); use if a proxy drops pooled connections and calls fail with random EOF errors")
	fs.BoolVar(&c.KeepTemp, "keep-temp", false, "Optional: Keep the scratch directory of each AI Remediation (copies of the patched source files and diffs) instead of deleting it; its path is logged. It can hold customer source code, so delete it when done")

	// Checkmarx One authentication flags. These mirror Cx1ClientGo.NewClient, which can't be used here
	// because it parses the flags itself before the HTTP transport (which depends on --proxy,
	// --insecure and --ca-cert) can be built.
	fs.StringVar(&c.APIKey, "apikey", "", "Checkmarx One API Key (alternative to the client ID and secret)")
	fs.StringVar(&c.ClientID, "client-id", "", "Checkmarx One Client ID")
	fs.StringVar(&c.ClientSecret, "client-secret", "", "Checkmarx One Client Secret")
	fs.StringVar(&c.BaseURI, "base-uri", "", "Checkmarx One platform URL, e.g. https://deu.ast.checkmarx.net")
	fs.StringVar(&c.BaseAuthURI, "base-auth-uri", "", "Checkmarx One IAM (authentication) URL")
	fs.StringVar(&c.Tenant, "tenant", "", "Checkmarx One tenant")
	fs.StringVar(&c.AccessToken, "access-token", "", "Optional: A valid access_token. If this value is provided, others will be ignored - the client will lose access when the token expires")
	fs.StringVar(&c.UserAgent, "user-agent", "cxscanremediate/"+version, "Optional: A custom user-agent string for all requests to Checkmarx One")

	documentEnv(fs)
	return fs, c
}

// Parse parses the command line args (without the program name) and fills every flag that was
// not given from its environment variable. A problem the flag package reports itself (an unknown
// flag, a bad value, or -h) is returned wrapped in ErrReported; -h is also flag.ErrHelp.
func Parse(name, version string, args []string) (*Config, error) {
	fs, c := NewFlagSet(name, version)
	if err := fs.Parse(args); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrReported, err)
	}
	if err := applyEnvDefaults(fs); err != nil {
		return nil, err
	}
	return c, nil
}

// Validate checks the selection and the counts before anything is sent to Checkmarx One, and
// returns the severities and engines to process. Counts above the per-run limit are reduced to it,
// with a warning. Every error is a usage error, worded for the log.
func (c *Config) Validate(logger *logrus.Logger) (map[string]bool, findings.Engines, error) {
	severities, err := findings.ParseSeverities(c.Severities)
	if err != nil {
		return nil, findings.Engines{}, fmt.Errorf("Invalid --severities: %w", err)
	}
	engines, err := parseEngines(c.Engines)
	if err != nil {
		return nil, findings.Engines{}, fmt.Errorf("Invalid --engines: %w", err)
	}
	if c.TriageCount, err = checkCount(logger, "triage-count", c.TriageCount); err != nil {
		return nil, findings.Engines{}, err
	}
	if c.RemediateCount, err = checkCount(logger, "remediate-count", c.RemediateCount); err != nil {
		return nil, findings.Engines{}, err
	}
	// Remediations are only ever delivered as pull requests.
	if c.RemediateCount > 0 && c.GitHubToken == "" {
		return nil, findings.Engines{}, errors.New("--remediate-count requires a GitHub token (--github-token or GITHUB_TOKEN) to publish pull requests")
	}
	return severities, engines, nil
}
