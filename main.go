// Process exit codes. This tool only runs after the scan has broken the pipeline's threshold,
// and nothing it does can clear that: AI Triage only ever proposes "Not Exploitable" (a human
// must still confirm), and remediations are only pull requests. So a completed run is never 0.
const (
	exitGateFailed = 1 // ran to completion; findings above threshold remain, so the pipeline must still fail
	exitUsage      = 2 // invalid flags (set by the flag package)
	exitError      = 3 // an operational failure (API, patch, or pull request error), or a fatal error
)

// errorRecorder logs non-fatal operational failures (triage, remediation, patch or PR errors) and
// counts them for the exit code.
type errorRecorder struct {
	logger *logrus.Logger
	count  int
}

func (e *errorRecorder) Errorf(format string, args ...interface{}) {
	e.count++
	e.logger.Errorf(format, args...)
}

// exitCodeFor returns the process exit code for a run that completed: never 0.
func exitCodeFor(operationErrors int) int {
	if operationErrors > 0 {
		return exitError
	}
	return exitGateFailed
}

// runState is what one run has read and done, so that finish can summarize it on every exit path.
type runState struct {
	logger   *logrus.Logger
	errs     *errorRecorder
	counters runCounters
	// set once the report is parsed
	results    *Cx1ClientGo.ScanResultSet
	severities map[string]bool
	engines    findings.Engines
	index      []findings.Finding // the findings this tool handles; their states are the current ones
}

// finish ends the run with a non-zero exit code so the calling pipeline still fails.
func (r *runState) finish(deepLink string) int {
	logRemainingSummary(r.logger, r.results, r.severities, r.engines, r.index, r.counters)
	code := exitCodeFor(r.errs.count)
	if code == exitError {
		r.logger.Errorf("Finished with %d error(s); exiting with code %d", r.errs.count, code)
	} else {
		r.logger.Warnf("Findings above the threshold remain (AI Triage only proposes a state and remediation needs a reviewed pull request); exiting with code %d so the pipeline fails", code)
	}
	r.logger.Infof("Review the results at %s", deepLink)
	return code
}

func main() {
	os.Exit(runMain(context.Background(), os.Args, os.Stdout))
}

// runMain runs the tool with the command line args (args[0] is the program name), logging to
// stdout, and returns the process exit code. It is the only place that decides the exit code.
func runMain(ctx context.Context, args []string, stdout io.Writer) int {
	logger := logrus.New()
	// Nothing in this tool calls logger.Fatal*: failures are returned and mapped to an exit code.
	// This is only a safety net, in case a library calls it.
	logger.ExitFunc = func(int) { os.Exit(exitError) }
	logger.SetLevel(logrus.InfoLevel)
	myformatter := &easy.Formatter{}
	myformatter.TimestampFormat = "2006-01-02 15:04:05.000"
	myformatter.LogFormat = "[%lvl%][%time%] %msg%\n"
	logger.SetFormatter(myformatter)
	logger.SetOutput(stdout)

	r := &runState{
		logger:   logger,
		errs:     &errorRecorder{logger: logger},
		counters: runCounters{Requested: map[string]bool{}, BranchExists: map[string]bool{}},
	}

	logger.Infof("Starting cxscanremediate %s", version)
	flags := flag.NewFlagSet(args[0], flag.ContinueOnError)
	LogLevel := flags.String("log-level", "INFO", "Log level: TRACE, DEBUG, INFO, WARNING, ERROR, FATAL")

	resultsFile := flags.String("report-file", "cx_result.json", "Path to JSON format report as generated by ast-cli --report-format json")
	numRemediate := flags.Int("remediate-count", 1, "Number of results to remediate, sorted by highest-priority and resultId")
	numTriage := flags.Int("triage-count", 0, "Number of results to triage, sorted by highest-priority and resultId")
	triageBatch := flags.Int("triage-batch-size", maxAIBatchSize, fmt.Sprintf("Number of results submitted to AI Triage together in one request (1-%d)", maxAIBatchSize))
	remediationBatch := flags.Int("remediation-batch-size", maxAIBatchSize, fmt.Sprintf("Number of results submitted to AI Remediation together in one request (1-%d)", maxAIBatchSize))
	engines := flags.String("engines", "sast,sca", "Focus only on these engines - comma separated list from: sast,sca")
	severity := flags.String("severities", "CRITICAL,HIGH", "Focus only on results of these severities - comma separated list from: CRITICAL,HIGH,MEDIUM,LOW,INFO")
	timeout := flags.Duration("timeout", 30*time.Minute, "Overall time limit for waiting on AI Triage and AI Remediation, e.g. 30m; 0 for no limit. Work that completes in time is still published as pull requests; unfinished work is abandoned and the run exits non-zero")
	sourceDir := flags.String("source-dir", ".", "Path to the root of the source code that was scanned, used as the base that remediation diffs are applied to in memory (never modified)")
	aiPollInterval := flags.Duration("ai-poll-interval", 0, "Optional: How often to ask whether an AI Triage or AI Remediation job has finished, e.g. 30s (default: the library's, 30s)")
	aiPollTimeout := flags.Duration("ai-poll-timeout", 0, "Optional: The longest to wait for one finding's AI Triage or AI Remediation job, e.g. 10m (default: the library's, 10m); --timeout still bounds the whole run")
	aiDetailsPollInterval := flags.Duration("ai-details-poll-interval", 0, "Optional: How often to retry fetching the result details of a finished AI job, e.g. 15s (default: the library's, 15s)")
	aiDetailsPollTimeout := flags.Duration("ai-details-poll-timeout", 0, "Optional: The longest to keep retrying that fetch, e.g. 1m (default: the library's, 1m)")

	// repo-scope (classic PAT) or Contents+Pull-requests write (fine-grained) permissions
	githubToken := flags.String("github-token", "", "GitHub token used to publish a pull request with the remediation changes; required when --remediate-count is above 0")
	repoFlag := flags.String("repo", "", "Target GitHub repository (owner/repo, HTTP(S) URL, or SSH URL; GitHub.com, GitHub Enterprise Server or a *.ghe.com host) for the pull request; derived from the Checkmarx One project's repoUrl if omitted")
	baseBranchFlag := flags.String("base-branch", "", "Branch to open the pull request against; defaults to the repository's default branch")
	prBranchFlag := flags.String("pr-branch", "", "Prefix for the names of the branches created for pull requests; each branch is this prefix plus the engine and result ID (default \"cx-remediate/\"). A finding whose branch already exists is skipped")

	proxy := flags.String("proxy", "", "Optional: Proxy server (http, https or socks5 URL) for outbound calls to Checkmarx One and GitHub; defaults to the HTTPS_PROXY environment variable")
	insecure := flags.Bool("insecure", false, "Optional: DISABLE TLS certificate verification for calls to Checkmarx One and GitHub (insecure; prefer --ca-cert)")
	caCert := flags.String("ca-cert", "", "Optional: Path to a PEM file with extra CA certificate(s) to trust for calls to Checkmarx One and GitHub, e.g. the CA of a TLS-inspecting proxy; added to the system trust store")

	noKeepAlive := flags.Bool("no-keep-alive", false, "Optional: Disable HTTP connection reuse (a new connection per request); use if a proxy drops pooled connections and calls fail with random EOF errors")
	keepTemp := flags.Bool("keep-temp", false, "Optional: Keep the scratch directory of each AI Remediation (copies of the patched source files and diffs) instead of deleting it; its path is logged. It can hold customer source code, so delete it when done")

	// Checkmarx One authentication flags. These mirror Cx1ClientGo.NewClient, which can't be used here
	// because it parses the flags itself before the HTTP transport (which depends on --proxy,
	// --insecure and --ca-cert) can be built.
	apiKey := flags.String("apikey", "", "Checkmarx One API Key (alternative to the client ID and secret)")
	clientID := flags.String("client-id", "", "Checkmarx One Client ID")
	clientSecret := flags.String("client-secret", "", "Checkmarx One Client Secret")
	cxURL := flags.String("base-uri", "", "Checkmarx One platform URL, e.g. https://deu.ast.checkmarx.net")
	iamURL := flags.String("base-auth-uri", "", "Checkmarx One IAM (authentication) URL")
	tenant := flags.String("tenant", "", "Checkmarx One tenant")
	token := flags.String("access-token", "", "Optional: A valid access_token. If this value is provided, others will be ignored - the client will lose access when the token expires")
	userAgent := flags.String("user-agent", "cxscanremediate/"+version, "Optional: A custom user-agent string for all requests to Checkmarx One")

	documentEnv(flags)
	if err := flags.Parse(args[1:]); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return exitUsage // the flag package has already reported the problem
	}
	if err := applyEnvDefaults(flags); err != nil {
		return usageError(logger, "%s", err)
	}

	// Validate the arguments before connecting to anything or spending any AI credits.
	level, err := parseLogLevel(*LogLevel)
	if err != nil {
		return usageError(logger, "Invalid --log-level: %s", err)
	}
	logger.SetLevel(level)

	severities, err := findings.ParseSeverities(*severity)
	if err != nil {
		return usageError(logger, "Invalid --severities: %s", err)
	}
	inScope, err := parseEngines(*engines)
	if err != nil {
		return usageError(logger, "Invalid --engines: %s", err)
	}
	if *numTriage, err = checkCount(logger, "triage-count", *numTriage); err != nil {
		return usageError(logger, "%s", err)
	}
	if *numRemediate, err = checkCount(logger, "remediate-count", *numRemediate); err != nil {
		return usageError(logger, "%s", err)
	}
	// Remediations are only ever delivered as pull requests.
	if *numRemediate > 0 && *githubToken == "" {
		return usageError(logger, "--remediate-count requires a GitHub token (--github-token or GITHUB_TOKEN) to publish pull requests")
	}

	httpTransport, err := transport.New(*proxy, *insecure, *caCert)
	if err != nil {
		return fatalError(logger, "Invalid proxy/TLS configuration: %s", err)
	}
	httpTransport.DisableKeepAlives = *noKeepAlive
	if *noKeepAlive {
		logger.Info("HTTP keep-alives disabled (--no-keep-alive)")
	}
	if *proxy != "" {
		logger.Infof("Using proxy")
	}
	if *insecure {
		logger.Warn("TLS certificate verification is DISABLED (--insecure); credentials and results can be intercepted. Prefer --ca-cert")
	}
	if *caCert != "" {
		logger.Infof("Trusting additional CA certificate(s) from %s", *caCert)
	}

	cxclient, err := Cx1ClientGo.NewClientWithOptions(Cx1ClientGo.Cx1ClientConfiguration{
		HttpClient:  &http.Client{Transport: httpTransport},
		Logger:      logger,
		HTTPHeaders: http.Header{"User-Agent": []string{*userAgent}},
		Auth: Cx1ClientGo.Cx1ClientAuth{
			APIKey:       *apiKey,
			ClientID:     *clientID,
			ClientSecret: *clientSecret,
			AccessToken:  *token,
		},
		Cx1Url: *cxURL,
		IAMUrl: *iamURL,
		Tenant: *tenant,
	})
	if err != nil {
		return fatalError(logger, "Error creating client: %s", err)
	}
	logger.Infof("Connected with %v", cxclient.String())

	var scan Cx1ClientGo.Scan

	data, err := os.ReadFile(*resultsFile)
	if err != nil {
		return fatalError(logger, "Failed to read report file %s: %s", *resultsFile, err)
	}

	scanId, count, results, err := cxclient.ParseReportJSON(data)
	if err != nil {
		return fatalError(logger, "Failed to parse report file %s: %s", *resultsFile, err)
	}

	scan, err = cxclient.GetScanByID(scanId)
	if err != nil {
		return fatalError(logger, "Failed to retrieve scan information for scan ID %s: %s", scanId, err)
	}
	logger.Infof("Target scan is %s", scan.String())

	deepLink := cxclient.GetBaseURL() + "/riskhub/" + scan.ProjectID

	// Pull requests are the only way remediations are delivered, so make sure they can be
	// created before any AI Triage or Remediation credits are spent.
	pr := prOptions{
		Token:      *githubToken,
		Transport:  httpTransport,
		Repo:       *repoFlag,
		BaseBranch: *baseBranchFlag,
		Branch:     *prBranchFlag,
		DeepLink:   deepLink,
	}
	if *numRemediate > 0 {
		pr, err = preflightPR(ctx, logger, cxclient, &scan, pr, *sourceDir)
		if err != nil {
			code := exitError
			if errors.Is(err, errConfig) {
				code = exitUsage
			}
			logger.Errorf("Pull request preflight check failed: %s", err)
			return code
		}
	}

	logger.Infof("Scan has %d SAST and %d SCA", len(results.SAST), len(results.SCA))

	// remembered so that finish can report what still counts against the threshold, per engine
	r.results, r.severities, r.engines = &results, severities, inScope

	index := findings.Collect(&results, severities, inScope)
	if len(index) == 0 {
		logger.Warn("No results are in a supported engine/severity for AI Triage or Remediation; the threshold break must be resolved manually")
		return r.finish(deepLink)
	}

	logger.Infof("Parsed scan ID %s report %s: %d results found with %d in scope", scanId, *resultsFile, count, len(index))
	findings.Prioritize(logger, index)
	r.index = index // the states in it are updated as the run goes on; finish summarizes them

	clientVars := cxclient.GetClientVars()
	if err := applyPollingOverrides(&clientVars, *aiPollInterval, *aiPollTimeout, *aiDetailsPollInterval, *aiDetailsPollTimeout); err != nil {
		return usageError(logger, "%s", err)
	}
	cxclient.SetClientVars(clientVars) // the library uses the details settings itself
	aiBudget := newBudget(*timeout)
	if !aiBudget.unlimited() {
		logger.Infof("AI Triage and Remediation share an overall time limit of %s", *timeout)
	}

	if *numTriage > 0 {
		candidates := findings.Pick(index, *numTriage, func(f *findings.Finding) bool { return findings.CanTriage(logger, f) })
		batchSize := clampBatchSize(logger, "triage-batch-size", *triageBatch)
		logger.Infof("Will auto-triage %d results (requested %d) in batches of up to %d", len(candidates), *numTriage, batchSize)

		for batch := range slices.Chunk(candidates, batchSize) {
			if aiBudget.expired() {
				r.errs.Errorf("Overall --timeout of %s reached; not submitting further AI Triage batches", *timeout)
				break
			}
			triageBatchOf(cxclient, logger, r.errs, &scan, batch, aiBudget, clientVars)
		}

		if useRefetchedStates && len(candidates) > 0 {
			// Whether a finding is exploitable is decided by the platform, so re-read the results
			// now that AI Triage has finished instead of interpreting its labels here.
			if err := refreshStates(logger, fetchResultsFor(cxclient, scan.ScanID, severities), index, aiBudget, stateRetryDelay, time.Sleep); err != nil {
				r.errs.Errorf("Could not re-read the scan results after AI Triage (%s); findings keep the state from the scan report, so none become eligible for AI Remediation because of the triage", err)
			}
		}
	}

	if *numRemediate > 0 {
		// A finding whose branch already exists was remediated by an earlier run (its pull
		// request is open, or was closed without deleting the branch), so it is skipped and
		// the next finding takes its place.

		ghClient, owner, repo, err := githubTarget(pr)
		if err != nil {
			r.errs.Errorf("Cannot check for existing branches (%s); skipping AI Remediation", err)
			return r.finish(deepLink)
		}
		eligible := func(f *findings.Finding) bool {
			if !findings.IsVerified(f) {
				return false
			}
			branch := branchFor(pr, f)
			exists, err := branchExists(ctx, ghClient, owner, repo, branch)
			switch {
			case err != nil:
				r.errs.Errorf("Could not check whether branch %q exists for %s: %s; skipping it", branch, f, err)
				return false
			case exists:
				r.counters.BranchExists[findings.Key(f)] = true
				logger.Infof("Skipping %s: branch %q already exists in %s/%s (remediated by an earlier run); delete the branch to retry", f, branch, owner, repo)
				return false
			}
			return true
		}

		candidates := findings.Pick(index, *numRemediate, eligible)
		for _, c := range candidates {
			r.counters.Requested[findings.Key(c)] = true
		}
		batchSize := clampBatchSize(logger, "remediation-batch-size", *remediationBatch)
		logger.Infof("Will auto-remediate %d results (requested %d, out of %d) in batches of up to %d", len(candidates), *numRemediate, len(index), batchSize)

		for batch := range slices.Chunk(candidates, batchSize) {
			if aiBudget.expired() {
				r.errs.Errorf("Overall --timeout of %s reached; not submitting further AI Remediation batches", *timeout)
				break
			}
			remediateBatchOf(cxclient, logger, r.errs, &scan, batch, *sourceDir, *keepTemp, pr, aiBudget, clientVars, &r.counters)
		}
	}

	return r.finish(deepLink)
}

// The AI Triage / AI Remediation backends are only known to handle this many results per request.
const maxAIBatchSize = 5

// clampBatchSize forces a user-supplied batch size into the supported 1..maxAIBatchSize range.
func clampBatchSize(logger *logrus.Logger, name string, n int) int {
	switch {
	case n < 1:
		logger.Warnf("--%s must be at least 1, using 1", name)
		return 1
	case n > maxAIBatchSize:
		logger.Warnf("--%s capped at %d (requested %d)", name, maxAIBatchSize, n)
		return maxAIBatchSize
	}
	return n
}

// toBuckets groups findings by engine into the request format shared by the AI endpoints.
func toBuckets(batch []*findings.Finding) []Cx1ClientGo.AIRequestBucket {
	var buckets []Cx1ClientGo.AIRequestBucket
	for _, f := range batch {
		i := slices.IndexFunc(buckets, func(b Cx1ClientGo.AIRequestBucket) bool { return b.Engine == f.Engine })
		if i < 0 {
			buckets = append(buckets, Cx1ClientGo.AIRequestBucket{Engine: f.Engine})
			i = len(buckets) - 1
		}
		buckets[i].AlternateIDs = append(buckets[i].AlternateIDs, f.AlternateID)
	}
	return buckets
}

// triageBatchOf submits the findings to AI Triage in a single request, then waits for each
// in turn. The jobs run concurrently on the platform, so only the first wait is long.
func triageBatchOf(cxclient *Cx1ClientGo.Cx1Client, logger *logrus.Logger, errs *errorRecorder, scan *Cx1ClientGo.Scan, batch []*findings.Finding, aiBudget budget, vars Cx1ClientGo.ClientVars) {
	for _, finding := range batch {
		logger.Infof("AI Auto-Triage %s finding: %s", finding.Severity, finding)
	}

	triageId, err := cxclient.RequestAITriages(scan.ScanID, toBuckets(batch))
	if err != nil {
		errs.Errorf("Failed to request triage: %s", err)
		return
	}
	logger.Infof("AI Triage request ID: %s", triageId)

	for _, finding := range batch {
		var status string
		var err error
		delay, max := aiBudget.pollTimeouts(vars.AIPollingDelaySeconds, vars.AIPollingMaxSeconds)
		if finding.Engine == "sca" {
			status, err = cxclient.PollSCAAITriageStatusWithTimeout(scan.ProjectID, finding.SimilarityID, finding.PackageID, delay, max)
		} else {
			status, err = cxclient.PollSASTAITriageStatusWithTimeout(scan.ProjectID, finding.SimilarityID, delay, max)
		}
		if err != nil && aiBudget.expired() {
			errs.Errorf("Overall --timeout reached before AI Triage finished for %s (%s); its state is unchanged", finding, err)
			continue
		}
		if err != nil {
			// the job may have already finished while an earlier finding in the batch was being polled
			logger.Warnf("Failed while polling AI Triage for %s (%s); trying to fetch the result anyway", finding, err)
		} else {
			logger.Infof("AI Triage for %s finished with status: %s", finding, status)
		}

		// The AI's assessment is only logged for information: the finding's state is read back
		// from the platform once the whole triage is done (see refreshStates).
		if finding.Engine == "sca" {
			details, err := cxclient.GetSCAAITriage(scan.ScanID, scan.ProjectID, finding.SimilarityID, finding.PackageID)
			if err != nil {
				logger.Warnf("Could not get the AI Triage assessment for %s: %s", finding, err)
				continue
			}
			logger.Infof("AI Triage results: exploitability %s, reachability %s", details.Analysis.Exploitability.Status, details.Analysis.Reachability.Status)
			finding.AI = &findings.Assessment{Exploitability: details.Analysis.Exploitability.Status, Reachability: details.Analysis.Reachability.Status}
			if !useRefetchedStates {
				finding.State = findings.AITriageState(logger, "AI Triage of "+finding.String(), *finding.AI, finding.State)
			}
			continue
		}

		details, err := cxclient.GetSASTAITriage(scan.ProjectID, finding.SimilarityID)
		if err != nil {
			logger.Warnf("Could not get the AI Triage assessment for %s: %s", finding, err)
			continue
		}
		logger.Infof("AI Triage results: %s (reachability %s, exploitability %s, attackability %s)", details.TriageStatus, details.ReachabilityStatus, details.ExploitabilityStatus, details.AttackabilityStatus)
		finding.AI = &findings.Assessment{Exploitability: details.TriageStatus, Reachability: details.ReachabilityStatus, ExploitabilityStatus: details.ExploitabilityStatus, AttackabilityStatus: details.AttackabilityStatus}
		if !useRefetchedStates {
			finding.State = findings.AITriageState(logger, "AI Triage of "+finding.String(), *finding.AI, finding.State)
		}
	}
}

// remediateBatchOf submits the findings to AI Remediation in a single request, then waits for
// each in turn and publishes its result. The jobs run concurrently on the platform, so only
// the first wait is long.
//
// Every remediation is computed in memory against the untouched source tree and published as
// its own independent pull request, so remediations that touch the same file do not interfere
// with one another. The source tree is never modified.
func remediateBatchOf(cxclient *Cx1ClientGo.Cx1Client, logger *logrus.Logger, errs *errorRecorder, scan *Cx1ClientGo.Scan, batch []*findings.Finding, sourceDir string, keepTemp bool, pr prOptions, aiBudget budget, vars Cx1ClientGo.ClientVars, counters *runCounters) {
	for _, finding := range batch {
		logger.Infof("AI Auto-Remediate finding: %s", finding)
	}

	remediationId, err := cxclient.RequestAIRemediations(scan.ScanID, scan.ProjectID, toBuckets(batch))
	if err != nil {
		errs.Errorf("Failed to request remediation: %s", err)
		return
	}
	logger.Tracef("Requested remediation id: %s", remediationId)

	for _, finding := range batch {
		delay, max := aiBudget.pollTimeouts(vars.AIPollingDelaySeconds, vars.AIPollingMaxSeconds)
		status, err := cxclient.PollAIRemediationStatusWithTimeout(scan.ScanID, finding.Engine, finding.AlternateID, delay, max)
		if err != nil && aiBudget.expired() {
			// jobs that finished earlier still get their pull request; only this unfinished one is abandoned
			errs.Errorf("Overall --timeout reached before AI Remediation finished for %s (%s); abandoning it", finding, err)
			continue
		}
		if err != nil {
			// the job may have already finished while an earlier finding in the batch was being polled
			logger.Warnf("Failed while polling remediation for %s (%s); trying to fetch the result anyway", finding, err)
		} else {
			logger.Tracef("Remediation for %s finished with status: %s", finding, status)
		}

		details, err := cxclient.GetAIRemediationDetails(scan.ScanID, finding.AlternateID)
		if err != nil {
			errs.Errorf("Failed while retrieving remediation for %s %s finding %s: %s", finding.Severity, finding.Engine, finding, err)
			continue
		}

		result, err := selectResult(details, finding.AlternateID)
		if err != nil {
			errs.Errorf("Skipping remediation for %s %s finding %s: %s", finding.Severity, finding.Engine, finding, err)
			continue
		}
		// only this finding's result is applied, so the pull request holds exactly its fix
		details.Results = []Cx1ClientGo.AIRemediationResult{result}

		changes, err := patch.Apply(logger, details, sourceDir, keepTemp)
		if err != nil {
			errs.Errorf("Skipping remediation for %s %s finding %s: %s", finding.Severity, finding.Engine, finding, err)
			continue
		}

		if publishRemediationPR(logger, errs, result, finding, changes, pr, branchFor(pr, finding)) {
			counters.PRsOpened++
		}
	}
}

// selectResult picks the remediation result for the finding with this alternate ID from the details
// the platform returned. The result is matched by its ID; if none matches and there is exactly one
// result, that one is used. A result that reports an error is not usable.
func selectResult(details Cx1ClientGo.AIRemediationDetails, alternateID string) (Cx1ClientGo.AIRemediationResult, error) {
	var result Cx1ClientGo.AIRemediationResult
	switch i := slices.IndexFunc(details.Results, func(r Cx1ClientGo.AIRemediationResult) bool { return r.ResultID == alternateID }); {
	case i >= 0:
		result = details.Results[i]
	case len(details.Results) == 1:
		result = details.Results[0]
	default:
		return result, fmt.Errorf("none of the %d remediation results returned is for result %s", len(details.Results), alternateID)
	}
	if result.Data.Error != nil {
		return result, fmt.Errorf("remediation %s reported an error: %s", result.RemediationID, *result.Data.Error)
	}
	return result, nil
}

// valueOrEnv returns the flag value, or the first non-empty of the environment variables when
// the flag is empty. Values are whitespace-trimmed.
func valueOrEnv(flagValue string, envNames ...string) string {
	if v := strings.TrimSpace(flagValue); v != "" {
		return v
	}
	for _, name := range envNames {
		if v := strings.TrimSpace(os.Getenv(name)); v != "" {
			return v
		}
	}
	return ""
}

// usageError reports an invalid command line and returns the usage exit code. It is used before any
// network call or AI credit has been used.
func usageError(logger *logrus.Logger, format string, args ...interface{}) int {
	logger.Errorf(format, args...)
	return exitUsage
}

// fatalError logs a failure that ends the run, at FATAL level but without exiting (unlike
// logger.Fatalf), and returns the operational-error exit code.
func fatalError(logger *logrus.Logger, format string, args ...interface{}) int {
	logger.Logf(logrus.FatalLevel, format, args...)
	return exitError
}
